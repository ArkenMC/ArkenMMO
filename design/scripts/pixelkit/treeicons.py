"""Original skill sigils, one 24x24 mask each. Every node state is generated from the same mask.

Rules: one bold shape, strokes at least 3 px, no real runic letters, no rotating hooks.
"""
import numpy as np

SIZE = 24


def grid(text):
    rows = [row.strip() for row in text.strip().split("\n")]
    if len(rows) != SIZE or any(len(row) != SIZE for row in rows):
        raise ValueError(f"icon grid must be {SIZE}x{SIZE}: {[len(r) for r in rows]}")
    return np.array([[ch == "#" for ch in row] for row in rows])


